def generate_markdown_report(report: dict) -> str:
    if report.get("error"):
        return f"# Error\n\n{report.get('message', 'Unknown error')}"

    lines = []
    lines.append(f"# RADIX Talent Match – Readiness Report")
    lines.append(f"**Candidate:** {report['candidate_name']}")
    lines.append(f"**Target Company:** {report['target_company']}")
    if report.get("benchmark_notice"):
        lines.append(f"**Benchmark source:** {report['benchmark_notice']}")
    lines.append(f"**Generated on:** {datetime.now().strftime('%d %B %Y, %I:%M %p')}")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(f"## Overall Readiness Score: **{report['readiness_score']}%**")
    lines.append(f"**Status:** {'READY' if report['is_ready'] else 'NOT READY YET'}")
    lines.append(f"**Threshold for Ready:** {report['readiness_threshold']}%")
    lines.append("")
    lines.append(f"**Total Estimated Learning Hours:** {report['total_estimated_learning_hours']} hours")
    lines.append("")

    if report["deal_breakers_count"] > 0:
        lines.append("## Critical Deal-Breaker Alerts")
        for db in report["deal_breakers_list"]:
            lines.append(f"- **{db['category']}**: Current {db['current']} → Required {db['required']} (Gap: {db['gap']})")
        lines.append("")
    else:
        lines.append("## Critical Deal-Breaker Alerts")
        lines.append("None – Great job!")
        lines.append("")

    what_if = report.get("what_if_recommendation", {})
    if what_if.get("recommended_skill_to_study"):
        lines.append("## Highest ROI Quick Win")
        lines.append(f"Focus on **{what_if['recommended_skill_to_study']}** first.")
        lines.append(f"Expected score boost: **+{what_if['projected_score_boost_pct']}%**")
        lines.append("")

    lines.append("## AI Career Coach Summary")
    lines.append(report.get("ai_candidate_agent_advice", "No advice generated."))
    lines.append("")

    lines.append("## Detailed Skill Gap Breakdown")
    lines.append("")
    lines.append("| Category | Your Level | Company Goal | Gap | Study Hours | Deal-Breaker? |")
    lines.append("|----------|------------|--------------|-----|-------------|---------------|")
    
    for item in report.get("per_skillset_gap_breakdown", []):
        deal = "YES" if item["is_deal_breaker"] else "No"
        lines.append(
            f"| {item['category']} | {item['candidate_level']} | {item['required_level']} | "
            f"{item['gap']} | {item['estimated_learning_hours']} | {deal} |"
        )

    lines.append("")
    lines.append("---")
    lines.append("*Generated by RADIX Talent Match – Role 04 Talent Check Engine*")
    
    return "\n".join(lines)

def save_report_to_file(report: dict, filename: str = None) -> str:
    if filename is None:
        safe_name = report.get("candidate_name", "candidate").replace(" ", "_")
        company = report.get("target_company", "company")
        filename = f"RADIX_Report_{safe_name}_{company}.md"

    content = generate_markdown_report(report)
    with open(filename, "w", encoding="utf-8") as f:
        f.write(content)
    return filename
