export function getSkillTopics(skillName: string, databaseTopics?: string[]): string[] {
  if (databaseTopics?.some((topic) => topic.trim())) return databaseTopics;
  const direct = seedTopics[skillName];
  if (direct) return direct;
  const normalized = skillName.trim().toLowerCase();
  const match = Object.entries(seedTopics).find(([name]) => name.toLowerCase() === normalized);
  return match?.[1] ?? [];
}
