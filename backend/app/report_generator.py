def generate_markdown_report(report: dict) -> str:
    if report.get("error"):
        return f"# Error\n\n{report.get('message', 'Unknown error')}"

    candidate_name = report.get("candidate_name", "Candidate")
    target_company = report.get("target_company") or report.get("company") or "Target Company"
    readiness_score = report.get("readiness_score", 0.0)
    is_ready = report.get("is_ready", False)
    threshold = report.get("readiness_threshold", 75.0)
    learning_hours = report.get("total_estimated_learning_hours", 0)
    deal_breakers_count = report.get("deal_breakers_count", 0)
    deal_breakers_list = report.get("deal_breakers_list", [])

    lines = []
    lines.append("# RADIX Talent Match - Candidate Readiness Report")
    lines.append(f"**Candidate:** {candidate_name}")
    lines.append(f"**Target Company:** {target_company}")
    lines.append(f"**Generated on:** {datetime.now().strftime('%d %B %Y, %I:%M %p')}")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(f"## Overall Readiness Score: **{readiness_score}%**")
    lines.append(f"**Status:** {'READY FOR HIRING' if is_ready else 'NEEDS PREPARATION'}")
    lines.append(f"**Threshold for Ready:** {threshold}%")
    lines.append("")
    lines.append(f"**Total Estimated Learning Hours:** {learning_hours} hours")
    lines.append("")

    lines.append("## Critical Deal-Breaker Alerts")
    if deal_breakers_count > 0:
        for db in deal_breakers_list:
            if isinstance(db, dict):
                lines.append(f"- **{db.get('category', 'Skill')}**: Current {db.get('current', 0)} -> Required {db.get('required', 0)} (Gap: {db.get('gap', 0)})")
            else:
                lines.append(f"- {db}")
    else:
        lines.append("None - Zero deal-breakers! Great job!")
    lines.append("")

    what_if = report.get("what_if_recommendation", {})
    if isinstance(what_if, dict) and what_if.get("recommended_skill_to_study"):
        lines.append("## Highest ROI Quick Win")
        lines.append(f"Focus on **{what_if.get('recommended_skill_to_study')}** first.")
        lines.append(f"Expected score boost: **+{what_if.get('projected_score_boost_pct', 0)}%**")
        lines.append("")

    lines.append("## AI Career Coach Summary")
    lines.append(report.get("ai_candidate_agent_advice", "No advice generated."))
    lines.append("")

    lines.append("## Detailed Skill Gap Breakdown (12 RADIX Competencies)")
    lines.append("")
    lines.append("| Category | Your Level | Company Goal | Gap | Study Hours | Deal-Breaker? |")
    lines.append("|----------|------------|--------------|-----|-------------|---------------|")
    
    breakdown = report.get("per_skillset_gap_breakdown") or report.get("skillset_gap") or []
    for item in breakdown:
        if isinstance(item, dict):
            deal = "YES" if item.get("is_deal_breaker") else "No"
            lines.append(
                f"| {item.get('category', 'N/A')} | {item.get('candidate_level', 0.0)} | "
                f"{item.get('required_level', 0.0)} | {item.get('gap', 0.0)} | "
                f"{item.get('estimated_learning_hours', 0)} | {deal} |"
            )

    lines.append("")
    lines.append("---")
    lines.append("*Generated by RADIX Talent Match - Role 04 Talent Check Engine*")
    
    return "\n".join(lines)

def save_report_to_file(report: dict, filename: str = None) -> str:
    if filename is None:
        safe_name = str(report.get("candidate_name", "candidate")).replace(" ", "_")
        company = report.get("target_company") or report.get("company") or "company"
        filename = f"RADIX_Report_{safe_name}_{company}.md"

    content = generate_markdown_report(report)
    with open(filename, "w", encoding="utf-8") as f:
        f.write(content)
    return filename
